def explain_prompt(passage: str, mode: str = "simple") -> list[dict[str, str]]:
    modes = {
        "simple": "Объясни этот отрывок простыми словами, понятными неподготовленному читателю, без спойлеров дальше по тексту.",
        "example": "Объясни этот отрывок и приведи современную бытовую аналогию или пример.",
        "context": "Объясни исторический и культурный контекст этого отрывка (эпоха, реалии, отсылки).",
    }
    instruction = modes.get(mode, modes["simple"])
    return [
        {"role": "system", "content": f"{instruction} Отвечай по-русски, 3-5 предложений, простым текстом без разметки."},
        {"role": "user", "content": passage},
    ]



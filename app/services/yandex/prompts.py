DEFAULT_PERSONA = "teacher"


def _spoiler_guard(total_pages: int, current_page: int) -> str:
    return (
        f"ВАЖНОЕ ОГРАНИЧЕНИЕ ПРО СПОЙЛЕРЫ.\n"
        f"Пользователь сейчас на странице {current_page + 1} из {total_pages}. Ниже дан текст "
        f"книги строго до этой страницы включительно — это единственное, что тебе разрешено "
        f"знать о сюжете. Даже если ты как модель уже «знаком» с этим произведением по "
        f"обучающим данным — веди себя так, будто твоё единственное знание о книге взято из "
        f"текста ниже. Никогда не раскрывай, не намекай и не подтверждай/опровергай события "
        f"или факты о персонажах, которые относятся к страницам ПОСЛЕ текущей. Если вопрос "
        f"требует такой информации — вежливо скажи, что дальше пока рано, и предложи вернуться "
        f"к вопросу позже по ходу чтения. Это правило важнее вежливости и важнее желания "
        f"угодить пользователю."
    )


def build_system_prompt(*, book_title: str, book_author: str, persona: str, current_page: int, total_pages: int) -> str:
    p = PERSONAS.get(persona, PERSONAS[DEFAULT_PERSONA])
    return (
        f"{p['voice']}\n\n"
        f"Ты обсуждаешь книгу «{book_title}» ({book_author}) с читателем в приложении "
        f"ReadMateAI. Отвечай по-русски (даже если книга на другом языке), лаконично — "
        f"обычно 3-6 предложений, если пользователь явно не просит подробнее. Пиши обычным "
        f"текстом без markdown и без HTML-тегов, форматирование добавит сам клиент.\n\n"
        f"{_spoiler_guard(total_pages, current_page)}"
    )


def build_context_block(story_so_far: str, recent_pages_text: str, current_page_text: str) -> str:
    parts = []
    if story_so_far:
        parts.append(f"[Краткое содержание прочитанного ранее]\n{story_so_far}")
    if recent_pages_text:
        parts.append(f"[Текст последних страниц]\n{recent_pages_text}")
    parts.append(f"[Текущая страница]\n{current_page_text}")
    return "\n\n".join(parts)


def recap_prompt(pages_text: str) -> list[dict[str, str]]:
    return [
        {
            "role": "system",
            "content": (
                "Ты помогаешь читателю вспомнить содержание книги. Сделай краткий связный "
                "рекап ТОЛЬКО по тексту ниже, 4-8 предложений, по-русски, без собственных "
                "домыслов и без забегания вперёд. Не упоминай, что это отрывок или цитата."
            ),
        },
        {"role": "user", "content": pages_text or "(текста пока нет)"},
    ]


